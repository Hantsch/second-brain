/** The words of a query, split as the user typed them. */
export function queryTerms(text: string): string[] {
  return text
    .split(/[^\p{L}\p{N}_]+/u)
    .map((term) => term.trim())
    .filter((term) => term.length > 0);
}

/**
 * The words of a query that carry its meaning, each once. If every word is a
 * stopword, all of them stay: whoever searches for „was“ alone means it.
 */
export function contentTerms(text: string): string[] {
  const terms = queryTerms(text);
  const seen = new Set<string>();
  const content = terms.filter((term) => {
    const folded = fold(term);
    if (STOPWORDS.has(folded) || seen.has(folded)) return false;
    seen.add(folded);
    return true;
  });
  return content.length > 0 ? content : terms;
}
